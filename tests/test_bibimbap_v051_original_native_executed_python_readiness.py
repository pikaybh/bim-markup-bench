class TrustedCopyDouble:
    """Distinct from executed Python; returned backend label must be ignored."""
    def __init__(self,source_fixture:Path,mode="ok"):
        self.fixture=source_fixture
        self.mode=mode
        self.calls=0
    def run(self,folder:Path,code:str)->dict:
        self.calls+=1
        if self.mode=="fail_exception":
            raise RuntimeError("Offline test double deliberately failed")
        if self.mode=="not_committed":
            return {"status":"ok","committed":False,
                    "backend":"linux_docker_sandbox"}
        if self.mode=="bad_ifc":
            (folder/"current.ifc").write_bytes(b"not IFC")
        else:
            shutil.copyfile(self.fixture, folder/"current.ifc")
        return {
            "status": "error" if self.mode=="after_commit_error" else "ok",
            "committed": True,
            "backend":"linux_docker_sandbox",
            "result":"TRUSTED_FIXTURE_NO_PYTHON_EVAL",
            "stdout":"","stderr":"",
        }


